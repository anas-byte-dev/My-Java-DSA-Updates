// Q12: WAP to print all numbers from 1 to 100 which are divisible by 7.
public class Q12 {
    public static void main(String[] args) {
        System.out.println("Numbers divisible by 7 from 1 to 100:");
        for (int i = 7; i <= 100; i += 7) {
            System.out.print(i + " ");
        }
        System.out.println();
    }
}
