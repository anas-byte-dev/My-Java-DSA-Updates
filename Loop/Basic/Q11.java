// Q11: WAP to print all odd numbers from 1 to 100.
public class Q11 {
    public static void main(String[] args) {
        System.out.println("Odd numbers from 1 to 100:");
        for (int i = 1; i <= 100; i += 2) {
            System.out.print(i + " ");
        }
        System.out.println();
    }
}
